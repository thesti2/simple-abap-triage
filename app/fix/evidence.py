"""Reproduce runs ("before" / "after") through ABAP Unit.

The ADT MCP cannot execute programs, but it can run ABAP Unit tests. So the worker rewrites the test include of a
local helper class (ZCL_TRIAGE_EVIDENCE, package $TMP -> no transport needed) with the program + variant to run,
activates it, runs its test, and reads the result (JSON between markers) from the test message.
The test calls ZCL_TRIAGE_RUNNER->run_job, i.e. a real background job named ZTRIAGE_RUN_<program>
(ignored by the job monitor, so reproduce runs never create new alerts).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any

EVIDENCE_CLASS = "ZCL_TRIAGE_EVIDENCE"
TEST_INCLUDE = "zcl_triage_evidence.clas.testclasses.abap"
_SAFE = re.compile(r"^[A-Z0-9_/]{1,40}$")

TEMPLATE = """*"* GENERATED by the ABAP Triage fix worker - overwritten on every reproduce run.
CLASS ltc_evidence DEFINITION FINAL FOR TESTING DURATION MEDIUM RISK LEVEL HARMLESS.
  PRIVATE SECTION.
    METHODS run FOR TESTING.
ENDCLASS.

CLASS ltc_evidence IMPLEMENTATION.
  METHOD run.
    DATA(ls_result) = NEW zcl_triage_runner( )->run_job( iv_program = '{program}' iv_variant = '{variant}' ).
    IF lines( ls_result-spool ) > 80.
      DELETE ls_result-spool FROM 81.
    ENDIF.
    DATA(lv_json) = /ui2/cl_json=>serialize( data = ls_result pretty_name = /ui2/cl_json=>pretty_mode-low_case ).
    cl_abap_unit_assert=>fail( msg    = 'TRIAGE_EVIDENCE'
                               detail = |@@EVIDENCE@@{{ lv_json }}@@END@@|
                               level  = if_aunit_constants=>critical
                               quit   = if_aunit_constants=>no ).
  ENDMETHOD.
ENDCLASS.
"""


RELEASE_TEMPLATE = """*"* GENERATED by the ABAP Triage fix worker - TR release run.
CLASS ltc_evidence DEFINITION FINAL FOR TESTING DURATION MEDIUM RISK LEVEL HARMLESS.
  PRIVATE SECTION.
    TYPES: BEGIN OF ty_result,
             released TYPE flag,
             status   TYPE trstatus,
             messages TYPE string_table,
           END OF ty_result.
    METHODS run FOR TESTING.
ENDCLASS.

CLASS ltc_evidence IMPLEMENTATION.
  METHOD run.
    DATA lv_released TYPE flag.
    DATA lv_status   TYPE trstatus.
    DATA lt_msg      TYPE bapiret2_t.
    CALL FUNCTION 'Z_TRIAGE_TR_RELEASE'
      EXPORTING iv_trkorr   = '{transport}'
      IMPORTING ev_released = lv_released
                ev_status   = lv_status
                et_messages = lt_msg.
    DATA(ls_result) = VALUE ty_result( released = lv_released status = lv_status
                                       messages = VALUE #( FOR m IN lt_msg ( |{{ m-type }}: {{ m-message }}| ) ) ).
    DATA(lv_json) = /ui2/cl_json=>serialize( data = ls_result pretty_name = /ui2/cl_json=>pretty_mode-low_case ).
    cl_abap_unit_assert=>fail( msg    = 'TRIAGE_RELEASE'
                               detail = |@@EVIDENCE@@{{ lv_json }}@@END@@|
                               level  = if_aunit_constants=>critical
                               quit   = if_aunit_constants=>no ).
  ENDMETHOD.
ENDCLASS.
"""
_TR = re.compile(r"^[A-Z0-9]{3}K\d{6}$")


def render_release_include(transport: str) -> str:
    transport = transport.upper()
    if not _TR.match(transport):
        raise ValueError(f"not a transport request number: {transport!r}")
    return RELEASE_TEMPLATE.format(transport=transport)


def parse_release_output(output: str) -> dict[str, Any]:
    """-> {"released": "X"|"", "status": "R"/"D"/..., "messages": [...]}"""
    m = re.search(r"@@EVIDENCE@@(.*?)@@END@@", output, re.S)
    if not m:
        raise ValueError(f"no release marker in unit test output: {output[:500]}")
    return json.loads(m.group(1).replace("\\'", "'"))


@dataclass
class Evidence:
    program: str
    variant: str
    status: str  # F finished, A cancelled, other = still running / unknown
    jobname: str = ""
    jobcount: str = ""
    joblog: list[str] = field(default_factory=list)
    spool: list[str] = field(default_factory=list)
    dump: dict[str, Any] = field(default_factory=dict)
    summary: str = ""

    @property
    def ok(self) -> bool:
        return self.status == "F"

    @property
    def label(self) -> str:
        return {"F": "FINISHED", "A": "CANCELLED"}.get(self.status, self.status or "UNKNOWN")


def render_test_include(program: str, variant: str) -> str:
    program, variant = program.upper(), variant.upper()
    if not (_SAFE.match(program) and _SAFE.match(variant)):
        raise ValueError(f"unsafe program/variant name: {program!r} / {variant!r}")
    return TEMPLATE.format(program=program, variant=variant)


def parse_unit_output(program: str, variant: str, output: str) -> Evidence:
    m = re.search(r"@@EVIDENCE@@(.*?)@@END@@", output, re.S)
    if not m:
        raise ValueError(f"no evidence marker in unit test output: {output[:500]}")
    raw = m.group(1).replace("\\'", "'")
    data = json.loads(raw)
    return Evidence(program=program, variant=variant, status=data.get("status", ""), jobname=data.get("jobname", ""),
                    jobcount=data.get("jobcount", ""), joblog=data.get("joblog") or [], spool=data.get("spool") or [],
                    dump=data.get("dump") or {}, summary=data.get("summary", ""))
